"""Generate protocol/vectors.json: press adverts (version 2, and version 1 for receivers that still
accept it), key-settings tags, and RFC 4231 HMAC-SHA256 cases.

    python3 protocol/gen_vectors.py > protocol/vectors.json
    python3 protocol/gen_vectors.py --c > firmware/test/test_packet/vectors.h
"""
import hashlib
import hmac
import json
import struct
import sys

MAGIC = b"TB"
VERSION = 2


def press_payload(device_id: bytes, key: bytes, counter: int, button: int, battery: int, history: bytes,
                  age: int) -> bytes:
    body = MAGIC + bytes([VERSION]) + device_id + struct.pack("<I", counter) + bytes([button, battery]) + history
    tag = hmac.new(key, body, hashlib.sha256).digest()[:8]
    return body + tag + bytes([age])


def press_payload_v1(device_id: bytes, key: bytes, counter: int, button: int, battery: int, age: int) -> bytes:
    body = MAGIC + bytes([1]) + device_id + struct.pack("<I", counter) + bytes([button, battery])
    tag = hmac.new(key, body, hashlib.sha256).digest()[:8]
    return body + tag + bytes([age])


def settings_tag(key: bytes, nonce: bytes, config: int) -> bytes:
    return hmac.new(key, b"TBcfg" + nonce + bytes([config]), hashlib.sha256).digest()[:8]


def c_bytes(h: str) -> str:
    return "{" + ", ".join("0x" + h[i:i + 2] for i in range(0, len(h), 2)) + "}"


def c_header(presses: list, settings: list, hmacs: list) -> str:
    out = ["// Generated by protocol/gen_vectors.py --c. Do not edit.", "#pragma once", "#include <stdint.h>", "#include <stddef.h>", ""]
    out.append("struct PressVector { uint8_t device_id[4]; uint8_t key[16]; uint32_t counter; uint8_t button, battery; uint8_t history[2]; uint8_t age; uint8_t payload[24]; };")
    out.append("static const PressVector PRESS_VECTORS[] = {")
    for p in presses:
        out.append(f"  {{{c_bytes(p['device_id'])}, {c_bytes(p['key'])}, {p['counter']}u, {p['button']}, {p['battery']}, {c_bytes(p['history'])}, {p['age']}, {c_bytes(p['payload'])}}},")
    out.append("};")
    out.append("struct SettingsVector { uint8_t key[16]; uint8_t nonce[8]; uint8_t config; uint8_t tag[8]; };")
    out.append("static const SettingsVector SETTINGS_VECTORS[] = {")
    for v in settings:
        out.append(f"  {{{c_bytes(v['key'])}, {c_bytes(v['nonce'])}, {v['config']}, {c_bytes(v['tag'])}}},")
    out.append("};")
    out.append("")
    for i, h in enumerate(hmacs):
        out.append(f"static const uint8_t HMAC_KEY_{i}[] = {c_bytes(h['key'])};")
        out.append(f"static const uint8_t HMAC_DATA_{i}[] = {c_bytes(h['data'])};")
        out.append(f"static const uint8_t HMAC_MAC_{i}[] = {c_bytes(h['mac'])};")
    out.append("struct HmacVector { const uint8_t *key; size_t key_len; const uint8_t *data; size_t data_len; const uint8_t *mac; };")
    out.append("static const HmacVector HMAC_VECTORS[] = {")
    for i, _ in enumerate(hmacs):
        out.append(f"  {{HMAC_KEY_{i}, sizeof HMAC_KEY_{i}, HMAC_DATA_{i}, sizeof HMAC_DATA_{i}, HMAC_MAC_{i}}},")
    out.append("};")
    return "\n".join(out)


def main() -> None:
    # Button codes: key in the low nibble, gesture (0 press, 1 hold, 2 double) in the high one.
    presses = []
    cases = [
        (bytes.fromhex("a1b2c3d4"), bytes(range(16)), 1, 0x01, 87, b"\0\0", 0),
        (bytes.fromhex("a1b2c3d4"), bytes(range(16)), 2, 0x02, 86, b"\x01\0", 37),
        (bytes.fromhex("a1b2c3d4"), bytes(range(16)), 3, 0x13, 86, b"\x02\x01", 1),
        (bytes.fromhex("00000000"), bytes(16), 0xFFFFFFFE, 0x24, 0xFF, b"\x04\x04", 0xFF),
        (bytes.fromhex("deadbeef"), bytes.fromhex("0f1e2d3c4b5a69788796a5b4c3d2e1f0"), 123456, 0x22, 100, b"\x12\x03", 5),
    ]
    for device_id, key, counter, button, battery, history, age in cases:
        presses.append({
            "device_id": device_id.hex(),
            "key": key.hex(),
            "counter": counter,
            "button": button,
            "battery": battery,
            "history": history.hex(),
            "age": age,
            "payload": press_payload(device_id, key, counter, button, battery, history, age).hex(),
        })

    presses_v1 = []
    cases_v1 = [
        (bytes.fromhex("a1b2c3d4"), bytes(range(16)), 1, 1, 87, 0),
        (bytes.fromhex("a1b2c3d4"), bytes(range(16)), 2, 2, 86, 37),
        (bytes.fromhex("00000000"), bytes(16), 0xFFFFFFFE, 1, 0xFF, 0xFF),
        (bytes.fromhex("deadbeef"), bytes.fromhex("0f1e2d3c4b5a69788796a5b4c3d2e1f0"), 123456, 2, 100, 5),
    ]
    for device_id, key, counter, button, battery, age in cases_v1:
        presses_v1.append({
            "device_id": device_id.hex(),
            "key": key.hex(),
            "counter": counter,
            "button": button,
            "battery": battery,
            "age": age,
            "payload": press_payload_v1(device_id, key, counter, button, battery, age).hex(),
        })

    settings = []
    for key, nonce, config in [
        (bytes(range(16)), bytes.fromhex("0001020304050607"), 0x00),
        (bytes(range(16)), bytes.fromhex("f0e1d2c3b4a59687"), 0x84),
        (bytes.fromhex("0f1e2d3c4b5a69788796a5b4c3d2e1f0"), bytes(8), 0xFF),
    ]:
        settings.append({"key": key.hex(), "nonce": nonce.hex(), "config": config,
                         "tag": settings_tag(key, nonce, config).hex()})

    # RFC 4231 test cases 1, 2, 3, 4 and 6 (6 has a key longer than the block size).
    rfc = [
        ("0b" * 20, b"Hi There".hex()),
        (b"Jefe".hex(), b"what do ya want for nothing?".hex()),
        ("aa" * 20, "dd" * 50),
        ("0102030405060708090a0b0c0d0e0f10111213141516171819", "cd" * 50),
        ("aa" * 131, b"Test Using Larger Than Block-Size Key - Hash Key First".hex()),
    ]
    hmacs = [{"key": k, "data": d,
              "mac": hmac.new(bytes.fromhex(k), bytes.fromhex(d), hashlib.sha256).hexdigest()}
             for k, d in rfc]

    if "--c" in sys.argv:
        print(c_header(presses, settings, hmacs))
        return
    print(json.dumps({"version": VERSION, "company_id": 0xFFFF, "press": presses, "press_v1": presses_v1,
                      "settings": settings, "hmac_sha256": hmacs}, indent=2))


if __name__ == "__main__":
    main()
